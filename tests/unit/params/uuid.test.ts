import { describe, expect, it } from 'vitest';
import { match } from '../../../src/params/uuid';

/**
 * Матчер стоит между адресной строкой и запросом к базе: всё, что он пропустил,
 * уедет в `where id = …`, где PostgreSQL разбирает значение как `uuid` и на
 * мусоре падает. Поэтому проверяются не «похожие» строки, а именно те, которыми
 * такой запрос ломают.
 */
describe('матчер идентификатора в адресе', () => {
	it('пропускает идентификаторы, которые выдаёт база', () => {
		expect(match('00000000-0000-4000-8000-0000000000a1')).toBe(true);
		expect(match('b0b4b0de-1234-4abc-9def-0123456789ab')).toBe(true);
		// Регистр в адресах встречается, и это тот же идентификатор.
		expect(match('B0B4B0DE-1234-4ABC-9DEF-0123456789AB')).toBe(true);
	});

	it('не пропускает то, на чём запрос к базе упал бы', () => {
		expect(match('abc')).toBe(false);
		expect(match('')).toBe(false);
		// Верная длина, но не шестнадцатеричные символы.
		expect(match('zzzzzzzz-0000-4000-8000-0000000000a1')).toBe(false);
		// Нулевая версия и нулевой вариант: такого идентификатора не бывает.
		expect(match('00000000-0000-0000-0000-000000000000')).toBe(false);
		// Лишние символы по краям — самый простой способ подмешать своё.
		expect(match(' 00000000-0000-4000-8000-0000000000a1')).toBe(false);
		expect(match('00000000-0000-4000-8000-0000000000a1/../admin')).toBe(false);
	});
});
