/**
 * Строка упоминания в колокольчике: начало комментария именами, без токенов,
 * и без чужих контактов — колокольчик виден на любом экране.
 */
import { describe, expect, it } from 'vitest';
import { mentionExcerpt, mentionToken } from '$lib/contracts/mentions';

describe('начало комментария в колокольчике', () => {
	it('называет упомянутого по имени и скрывает почту и телефон, а числа оставляет', () => {
		const body = `${mentionToken('Смирнова Ольга', '6f1c1a53-4c1e-4c5e-9d0b-2b6f0f7c1a11')} позвоните\nИванову: +7 (900) 123-45-67, ivanov@vuz.example — план 25 студентов 2026 2027`;

		expect(mentionExcerpt(body)).toBe(
			'@Смирнова Ольга позвоните Иванову: [телефон скрыт], [почта скрыта] — план 25 студентов 2026 2027'
		);
	});
});
