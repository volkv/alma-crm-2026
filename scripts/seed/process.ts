/**
 * Процессы групп на демонстрационном стенде.
 *
 * Сами группы и соответствие «вид контрагента → группа» кладёт миграция: без
 * них у взаимодействия нет процесса, и это не демонстрационные данные, а часть
 * продукта. Набору остаётся завести действующую редакцию каждой группы —
 * четырнадцать стадий работы с вузом и короткий процесс обучения лиц.
 *
 * Стадии кладёт сид, а не миграция, намеренно: навязывать заказчику наши
 * четырнадцать стадий установкой схемы незачем, а заводятся они одной кнопкой.
 */
import type { Tx } from '$lib/server/db/transaction';
import {
	B2B_GROUP_KEY,
	B2B_PROCESS,
	B2C_GROUP_KEY,
	B2C_PROCESS
} from '$lib/server/stages/definitions';
import { ensureProcess } from '$lib/server/stages/process';

/**
 * Действующие редакции обеих групп. Идемпотентно: у группы, где процесс уже
 * описан, ничего не переписывается — на стенде могли применить изменения
 * руками, и сид не имеет права их отменять.
 */
export async function seedProcesses(tx: Tx): Promise<void> {
	await ensureProcess(tx, B2B_GROUP_KEY, B2B_PROCESS);
	await ensureProcess(tx, B2C_GROUP_KEY, B2C_PROCESS);
}
