/**
 * Данные «Договоров и лицензий» для карточки: то, что `load` в
 * `card.server.ts` кладёт в `data.moduleData.contracts`. Тип отдельно от
 * серверной части, чтобы панель брала его, не касаясь серверного файла.
 */
export type ContractsCardData = {
	/**
	 * Сколько договоров у основной стороны: нет ни одного — панель вместо
	 * выбора ведёт в карточку организации создать договор. `null` — править
	 * запись нельзя, и выбирать договор некому.
	 */
	contractCount: number | null;
	/** Основная сторона дела, в карточке которой ведут её договоры. */
	organizationId: string | null;
};
