/*
 * Открыта ли палитра поиска.
 *
 * Состояние на весь документ, а не на компонент: открывают палитру из трёх мест
 * — кнопка в меню разделов, кнопка в нижней панели телефона и Ctrl+K на любом
 * экране, — а рисует её одна оболочка. Передавать флаг вниз пропсами через
 * меню и панель значило бы вести один и тот же обработчик двумя маршрутами.
 *
 * На сервере это всегда «закрыта»: меняют состояние только обработчики событий
 * браузера, поэтому поделённый между запросами модуль остаётся неизменным — то
 * же соглашение, что у темы (`$lib/theme.svelte.ts`).
 */
let open = $state(false);

export const search = {
	get open(): boolean {
		return open;
	},
	set open(next: boolean) {
		open = next;
	},
	/** Открыть палитру: то, что делают кнопка поиска и Ctrl+K. */
	show(): void {
		open = true;
	}
};
