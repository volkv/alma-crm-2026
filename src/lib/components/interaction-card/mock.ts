import { toast } from 'svelte-sonner';

/**
 * Нажатие на макете. Кнопки на витрине выглядят и ведут себя как настоящие —
 * фокус, наведение, нажатие, — но команд не отдают: это макет раскладки, и
 * записи демонстрационного набора он не меняет. Тост говорит об этом словами,
 * чтобы нажатие не выглядело как «ничего не произошло».
 */
export function mockAction(label: string): void {
	toast(`«${label}»`, { description: 'Макет: на витрине действия не выполняются.' });
}
