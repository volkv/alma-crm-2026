/**
 * Блок «С сайта вуза» в формах карточки дела: что сказать о состоянии отчёта
 * сайта и как долго ждать, пока его прочитают.
 *
 * Отчёт читается в фоне (сервер прогревает его, когда нужен), и форма не
 * держит сотрудника: пока идёт чтение, блок говорит «подтягиваем» и
 * переспрашивает сервер несколько раз с паузой. Бесконечного опроса нет — сайт
 * вуза бывает медленным или лежит, и форма работает и без него.
 */
import type { SiteSourceView } from '$lib/contracts/organization-card';

/** Пауза между повторными вопросами, пока сайт читается. */
export const SITE_POLL_INTERVAL_MS = 4000;

/** Сколько раз переспросить: около полуминуты — дольше сайт вуза не читается. */
export const SITE_POLL_ATTEMPTS = 8;

/** Что именно предлагается: подразделения или люди — для подписей. */
export type SiteOfferKind = 'units' | 'people';

/**
 * Строка состояния блока; `null` — сказать нечего, показывается список.
 *
 * `total` — сколько записей такого вида на сайте всего, вместе с уже
 * заведёнными, `shown` — сколько осталось предложить; `exhausted` — повторные
 * вопросы кончились, а сайт всё ещё читается.
 */
export function siteSourceMessage(
	source: SiteSourceView,
	kind: SiteOfferKind,
	counts: { total: number; shown: number; exhausted: boolean }
): string | null {
	const what = kind === 'units' ? 'подразделения' : 'руководителей';

	switch (source.state) {
		case 'warming':
			return counts.exhausted
				? 'Сайт вуза отвечает долго. Сведения появятся здесь, когда откроете форму позже'
				: 'Подтягиваем сведения с сайта…';
		case 'no_site':
			return `У вуза не указан сайт — ${what} с него не подтянуть`;
		case 'disabled':
			return 'Внешние источники выключены в настройках: сведения с сайта не читаются';
		case 'unreadable':
			return kind === 'units'
				? 'На сайте вуза не прочитался подраздел «Структура»'
				: 'На сайте вуза не прочитались «Структура» и «Руководство»';
		case 'ready':
			if (counts.total === 0) {
				return kind === 'units'
					? 'На сайте вуза подразделения не перечислены'
					: 'На сайте вуза руководители не названы';
			}

			return counts.shown === 0 ? `Все ${what} с сайта уже в справочнике` : null;
	}
}
