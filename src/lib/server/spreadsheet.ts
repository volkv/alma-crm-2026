/**
 * Текст, который уходит в таблицу.
 *
 * Excel, LibreOffice и Google Sheets читают ячейку как формулу, если та
 * начинается с `=`, `+`, `-` или `@`. Название организации, имя файла или
 * строка, приехавшая из чужой системы, попадают в выгрузку как есть — и
 * `=HYPERLINK("http://…")` выполнится у того, кто её открыл. Это не теория:
 * тем же способом из таблицы утекают её собственные ячейки.
 *
 * Обезвреживает апостроф впереди: им таблицы помечают «это текст», и в самой
 * ячейке он не показывается. Кавычки вокруг значения от формулы не спасают —
 * таблица разбирает содержимое уже после них.
 *
 * Функция одна на все выгрузки продукта (книга показателей, журнал действий,
 * таблица выгрузки из системы обучения) намеренно: три копии списка символов
 * расходятся молча, и расходится та, про которую забыли.
 */

/**
 * Символы, с которых начинается формула. Табуляция и возврат каретки в том же
 * списке: таблица съедает их при разборе, и следующий за ними знак равенства
 * оказывается первым.
 */
const FORMULA_STARTS = ['=', '+', '-', '@', '\t', '\r'];

export function spreadsheetText(value: string): string {
	return FORMULA_STARTS.some((start) => value.startsWith(start)) ? `'${value}` : value;
}
