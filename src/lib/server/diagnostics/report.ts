/**
 * Отчёт самодиагностики: из чего он состоит и как из строк выводится итог.
 *
 * Здесь нет ни одного сетевого вызова — только данные и правила над ними, чтобы
 * два обещания экрана проверялись без стенда: итог «работает без интернета»
 * считается по одним обязательным связям, а адрес, попавший на экран, не
 * уносит ни пароля, ни токена.
 */

/**
 * Состояние связи.
 *
 * - `ok` — связь ответила в пределах таймаута;
 * - `failed` — не ответила или ответила не тем;
 * - `not_configured` — адрес в установке не задан, и связь не используется;
 * - `disabled` — внешний источник выключен флагом в настройках;
 * - `not_checked` — связь не проверяют при открытии страницы: это выход наружу,
 *   и он делается только по отдельной кнопке.
 */
export type LinkStatus = 'ok' | 'failed' | 'not_configured' | 'disabled' | 'not_checked';

export type LinkState = {
	status: LinkStatus;
	/** Пояснение словами: причина отказа или почему связь не проверялась. */
	detail: string | null;
	/** Время ответа — только у проверенных связей. */
	latencyMs: number | null;
};

/**
 * Обязательна ли связь для основных сценариев.
 *
 * - `required` — локальная зависимость контура: без неё не работает вход,
 *   карточка, документы или отчёты;
 * - `allowed` — разрешённая связь внутри сети заказчика (CMS, система обучения,
 *   почтовый релей): без неё выключается одно направление, остальное работает;
 * - `external` — выход в интернет; отключается флагом, и без него форма
 *   организации заполняется вручную.
 */
export type LinkKind = 'required' | 'allowed' | 'external';

export type DiagnosticLink = {
	id: string;
	name: string;
	purpose: string;
	kind: LinkKind;
	/** Адрес без учётных данных и параметров; `null` — адрес не задан. */
	address: string | null;
	state: LinkState;
};

export type DiagnosticsReport = {
	checkedAt: string;
	links: DiagnosticLink[];
	/** Основные сценарии работают без интернета: ответили все обязательные связи. */
	offlineReady: boolean;
	/**
	 * Узлы внутри сети, куда обмену разрешено ходить (`OUTBOUND_ALLOWED_HOSTS`):
	 * имена, адреса и сети. Пустой — открыты только публичные адреса.
	 */
	outboundAllowList: readonly string[];
};

/**
 * Итог «основные сценарии работают без интернета».
 *
 * Считается только по обязательным связям: отказ CMS, почты или Dadata
 * выключает своё направление, но не вход, не карточку и не отчёты. Пустой
 * список обязательных — не «да»: отчёт без базы и хранилища ничего не доказал.
 */
export function isOfflineReady(links: readonly DiagnosticLink[]): boolean {
	const required = links.filter((link) => link.kind === 'required');

	return required.length > 0 && required.every((link) => link.state.status === 'ok');
}

/**
 * Адрес для экрана: схема, узел, порт и путь — без имени, пароля, строки
 * запроса и фрагмента.
 *
 * Пароль базы и Redis лежит прямо в строке подключения, а токен веб-сервиса
 * системы обучения бывает в параметре запроса (`?wstoken=`). Показывать на
 * экране нужно, куда система ходит, а не чем она там представляется.
 */
export function displayAddress(raw: string): string {
	const url = new URL(raw);
	const path = url.pathname === '/' ? '' : decodeURI(url.pathname);

	return `${url.protocol}//${url.host}${path}`;
}

/**
 * Учётные данные внутри адресов, которые попали в текст ошибки.
 *
 * Причину отказа пишет чужая библиотека, и она вольна процитировать строку
 * подключения целиком. Вырезается часть `//имя:пароль@` у любого адреса в
 * тексте — какой бы адрес библиотека ни процитировала.
 */
export function hideCredentials(message: string): string {
	return message.replace(/\/\/[^/\s@]+@/g, '//');
}
