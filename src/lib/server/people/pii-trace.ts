/**
 * След просмотра персональных данных.
 *
 * Закон требует знать, кто видел контакты человека, но событие на каждую
 * строку списка превращает журнал в свалку: открытая страница справочника —
 * это двадцать пять раскрытых записей, а отчёт по одному вузу — сотня. Поэтому
 * след собирается по запросу: чтения людей объявляют себя областью сбора,
 * сериализатор докладывает сюда каждого человека, чьи контакты показал без
 * маскирования, и когда последняя такая область закрылась, в журнал уходит
 * одно событие `people.pii_viewed` со списком идентификаторов.
 *
 * Область сбора — это чтение, а не запрос целиком: HTTP-слоя здесь нет и быть
 * не должно (сервисы про него не знают). Зато загрузчики страниц запускают
 * свои чтения одной `Promise.all`, поэтому вложенные и параллельные области
 * складываются в одну, и запрос действительно оставляет одну запись.
 */
import type { ActorContext } from '../actor';
import { recordAuditEvent } from '../audit';
import type { Tx } from '../db/transaction';

type Trace = {
	/** Сколько областей сбора сейчас открыто для этого запроса. */
	depth: number;
	personIds: Set<string>;
};

/**
 * Открытые области по идентификатору запроса. Запись живёт ровно столько,
 * сколько идёт чтение: последняя закрывшаяся область уносит её с собой, в том
 * числе когда чтение кончилось ошибкой.
 */
const traces = new Map<string, Trace>();

/**
 * Область сбора следа. Вложенный вызов присоединяется к уже открытой области
 * того же запроса, а не заводит свою: карточка человека читает и его самого, и
 * его роли, и это одно обращение к персональным данным, а не два.
 *
 * `tx` передаёт тот, кто открывает область внутри своей транзакции: тогда
 * событие пишется её же исполнителем. Без этого запись уходила бы другим
 * соединением, пока транзакция держит своё, и десяток одновременных операций
 * запирал бы пул — все ждут второго соединения, отдать первое некому.
 */
export async function withPiiTrace<TResult>(
	ctx: ActorContext,
	read: () => Promise<TResult>,
	tx?: Tx
): Promise<TResult> {
	const trace = traces.get(ctx.requestId) ?? { depth: 0, personIds: new Set<string>() };

	trace.depth += 1;
	traces.set(ctx.requestId, trace);

	let succeeded = false;

	try {
		const result = await read();
		succeeded = true;

		return result;
	} finally {
		trace.depth -= 1;

		if (trace.depth === 0) {
			traces.delete(ctx.requestId);

			if (trace.personIds.size > 0) {
				// Упавшее чтение пишет событие вне транзакции, даже когда её
				// исполнитель известен. Причин две. Транзакция после ошибки базы уже
				// в состоянии `25P02`: вставка в ней не пройдёт и заменит собой
				// исходную ошибку, а на неё смотрит вызывающий — приём заявки,
				// например, различает по ней гонку на уникальности и отвечает
				// повтором. И по смыслу так же: контакты человеку уже показали, а
				// откат унёс бы запись об этом.
				await recordAuditEvent(
					ctx,
					{
						type: 'people.pii_viewed',
						outcome: 'success',
						details: { personIds: [...trace.personIds] }
					},
					succeeded ? tx : undefined
				);
			}
		}
	}
}

/**
 * Отметить, что контакты человека показали без маскирования. Зовёт её
 * сериализатор и только он: маскирование живёт в одном месте, и след просмотра
 * обязан жить там же, иначе они разойдутся.
 *
 * Чтение вне области сбора следа не оставляет — так задумано: область
 * открывают чтения людей, а прочие вызовы сериализатора (сид, фоновые задачи)
 * никому контакты не показывают.
 */
export function notePiiView(ctx: ActorContext, personId: string): void {
	traces.get(ctx.requestId)?.personIds.add(personId);
}
