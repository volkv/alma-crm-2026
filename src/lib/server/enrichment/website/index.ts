/**
 * Сайт организации по реквизитам из реестра — цепочка, которой пользуется
 * паспорт по ЕГРЮЛ (`registryPassport`) и заведение организации из выбранной
 * строки реестра (`pick.ts`).
 *
 * Это упрощение: подключены только бесплатные источники — статический снимок
 * открытого мониторинга эффективности вузов Минобрнауки (`university-sites.ts`)
 * и догадка по домену почты из выписки (`email-domain.ts`). Снимок устаревает
 * с каждым годом и не покрывает колледжи, филиалы и вузы вне мониторинга, а
 * почты на бесплатном тарифе Dadata в выписке нет вовсе (`emails: null`), так
 * что догадке чаще всего не из чего исходить.
 *
 * В рабочей эксплуатации нужен платный тариф Dadata. Сайт отдаёт тот же
 * `findById/party` на тарифе «Максимальный» — в `data.sites[]` и
 * `data.emails[]`, — или отдельный метод `findById/brand` (`data.domain`,
 * оплачивается за запрос). И то и другое подключается ещё одним адаптером порта
 * (`port.ts`) в начало цепочки, без правки вызывающих; так же подключается
 * любой другой источник — реестр лицензий, собственная выгрузка заказчика.
 * Платному адаптеру понадобится свой кэш: паспорт по реестру собирается на
 * каждую подсказку при наборе.
 */
