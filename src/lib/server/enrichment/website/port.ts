/**
 * Порт «сайт организации по реквизитам» и сборка цепочки его адаптеров.
 *
 * Сайт нужен карточке не для красоты: по нему читается раздел «Сведения об
 * образовательной организации» (`sveden.ts`), а оттуда — наименования,
 * кандидаты в контакты и программы. В ЕГРЮЛ сайта нет, и ни один источник не
 * знает его про всех: справочник вузов покрывает головные вузы, почта из
 * выписки есть не у каждой организации. Поэтому источников несколько, у
 * каждого свой адаптер, а спрашиваются они по очереди — первый ответ и есть
 * предложение.
 *
 * Поиск сайта — услуга, а не условие: заведение организации из реестра не
 * должно падать оттого, что справочник не прочитался или поставщик не ответил.
 * Любой сбой адаптера пишется в журнал сервера и превращается в «не знаю», и
 * спрашивается следующий; не ответил никто — поле пустое, и сайт сотрудник
 * вводит сам.
 */
import type { FieldSource } from '$lib/contracts/enrichment';
import { normalizeWebsite } from '../sveden';

/**
 * Что известно об организации к моменту поиска: реквизиты из выписки. ИНН —
 * ключ, по которому организацию узнают справочники; почта — материал для
 * догадки по домену.
 */
export type WebsiteQuery = {
	inn: string | null;
	emails: readonly string[];
};

/** Ответ адаптера: адрес, откуда он взят и что о нём сказать сотруднику. */
export type WebsiteFinding = {
	/**
	 * Схема и узел без пути (`normalizeWebsite`). Кириллический домен — уже в
	 * punycode (`https://xn--80ahg0a.xn--p1ai`): так его пропускает проверка
	 * адреса в карточке, и так его понимает любой клиент HTTP.
	 */
	website: string;
	/** Источник в паспорте и в журнале происхождения. */
	source: FieldSource;
	/**
	 * Момент, к которому относится ответ, если он старше самого поиска: у
	 * статического снимка это дата выгрузки, и сотрудник должен её видеть. Без
	 * него значение датируется ответом реестра.
	 */
	fetchedAt?: string;
	/** Замечание в паспорт: насколько адресу можно верить. `null` — нечего сказать. */
	note: string | null;
};

/**
 * Адаптер порта. Сеть, таймаут и кэш — забота самого адаптера: цепочка знает
 * только, что ответ может прийти не сразу и может не прийти вовсе.
 */
export type WebsiteFinder = {
	/** Имя в журнале сервера — чтобы по записи о сбое было ясно, кто отказал. */
	name: string;
	find(query: WebsiteQuery): Promise<WebsiteFinding | null> | WebsiteFinding | null;
};

export type FindWebsite = (query: WebsiteQuery) => Promise<WebsiteFinding | null>;

/**
 * Цепочка адаптеров: по порядку, первый пригодный ответ выигрывает.
 *
 * Адрес каждого ответа ещё раз проходит `normalizeWebsite` здесь, а не только
 * в адаптере: строка приехала из внешнего источника и станет адресом в
 * карточке, и гарантия «origin или ничего» не должна зависеть от того, кто
 * писал адаптер. Непригодный адрес — такой же «не знаю», как и сбой.
 */
export function chainWebsiteFinders(finders: readonly WebsiteFinder[]): FindWebsite {
	return async (query) => {
		for (const finder of finders) {
			let finding: WebsiteFinding | null;

			try {
				finding = await finder.find(query);
			} catch (error) {
				console.warn(`[enrichment] источник сайта «${finder.name}» не ответил`, error);
				continue;
			}

			const website = finding === null ? null : normalizeWebsite(finding.website);

			if (finding !== null && website !== null) {
				return { ...finding, website };
			}
		}

		return null;
	};
}
