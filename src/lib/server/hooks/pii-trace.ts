import type { Handle } from '@sveltejs/kit';
import { actorFromEvent } from '../actor';
import { withPiiTrace } from '../people/pii-trace';

/**
 * Область сбора следа просмотра персональных данных на весь запрос.
 *
 * Чтения людей открывают свои области сами, и параллельные складываются в
 * одну. Но загрузчик карточки читает в несколько приёмов: сначала запись и
 * стороны, потом справочник основной стороны, потом данные модулей, — и каждое
 * последовательное чтение закрывало бы свою область и писало своё событие. В
 * журнале это выглядело как две-три одинаковые строки «Просмотр контактов» с
 * одним номером запроса. Внешняя область держит сбор открытым до конца
 * обработки, и запрос оставляет ровно одно событие — сколько бы приёмов ни
 * понадобилось загрузчику и действию формы вместе.
 *
 * Стоит после `session`: событие пишется от имени того, кто смотрел. Фоновые
 * задачи через хуки не идут и по-прежнему собирают след своими областями.
 */
export const piiTrace: Handle = ({ event, resolve }) =>
	withPiiTrace(actorFromEvent(event), () => Promise.resolve(resolve(event)));
