/**
 * Перенаправление, которым хук отвечает сам.
 *
 * `redirect()` из SvelteKit — это исключение: брошенное в хуке, оно пролетает
 * мимо всей цепочки, и ответ на него собирается уже за её пределами. Значит,
 * ни заголовки безопасности, ни `x-request-id` на такой ответ не попадают —
 * внешние хуки его попросту не видят. Ответ, собранный здесь, возвращается
 * наружу как обычный: каждый внешний хук успевает дописать своё, а для запроса
 * данных клиентского маршрутизатора SvelteKit сам переводит его в тот вид,
 * который понимает браузерная часть.
 *
 * Цена ровно одна: cookie, отложенные в `event.cookies`, SvelteKit подставляет
 * только ответу, вышедшему из маршрута. Поэтому тот, кто их ставит, дописывает
 * их сюда сам — см. хук `session`.
 */
export function hookRedirect(location: string): Response {
	return new Response(null, { status: 303, headers: { location } });
}
