/**
 * Общий пароль демонстрационных учётных записей — тот, что карточка на странице
 * входа показывает рядом с тремя именами входа.
 *
 * Пароль принадлежит **каталогу**, а не приложению: своих паролей у системы нет
 * вовсе, а этот заводится импортом realm (`keycloak/realm-lct.json`). Приложение
 * его не проверяет и не хранит — оно только повторяет его на экране, чтобы
 * зритель публичного стенда мог войти, не спрашивая никого. Отсюда и отдельная
 * переменная окружения, а не чтение realm: развёртывание обязано сказать
 * отдельным действием, что пароль стенда публичный.
 *
 * Разбор значения живёт в схеме конфигурации (`DEMO_PASSWORD_HINT` в
 * `server/config.ts`), как у всякой переменной окружения: испорченное значение
 * обязано ронять старт, а не всплывать пустой карточкой на первом заходе. Здесь
 * остался единственный вопрос, который решает не конфигурация, — показывать ли
 * подсказку вообще.
 */

/**
 * Пароль для карточки входа или `null`, если показывать нечего.
 *
 * `null` — это два случая, и оба законные: установка работает не в
 * демонстрационном режиме (тогда подсказывать чужой пароль не за чем), либо
 * пароль не задан вовсе — так поднимают стенд, пароль которого выдают лично.
 */
export function demoPasswordHint(hint: string | null, demoMode: boolean): string | null {
	return demoMode ? hint : null;
}
