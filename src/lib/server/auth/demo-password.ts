/**
 * Общий пароль демонстрационных учётных записей — тот, что карточка на странице
 * входа показывает рядом с тремя именами входа.
 *
 * Пароль принадлежит **каталогу**, а не приложению: своих паролей у системы нет
 * вовсе, а этот заводится импортом realm (`keycloak/realm-lct.json`). Приложение
 * его не проверяет и не хранит — оно только повторяет его на экране, чтобы
 * зритель публичного стенда мог войти, не спрашивая никого. Отсюда и отдельная
 * переменная окружения, а не чтение realm: развёртывание обязано сказать
 * отдельным действием, что пароль стенда публичный.
 *
 * Значение приходит из `DEMO_PASSWORD_HINT` и проверяется здесь же: нет
 * переменной — нет и подсказки; есть — показывается. Пустая строка равна «не
 * задано» по тому же правилу, что и у остальных необязательных переменных
 * (`server/config.ts`): Compose подставляет пустое значение там, где переменной
 * нет в `.env`. А вот значение, которое задали и испортили, молча не
 * пропускается: пустая строка вместо пароля на карточке — это не подсказка.
 */
import { z } from 'zod';

/**
 * Что считается паролем стенда. Потолок длины — от опечатки вида
 * `DEMO_PASSWORD_HINT=$(cat .env)`: на экран уходит строка, а не файл.
 */
const hintSchema = z
	.string()
	.trim()
	.min(1, { error: 'DEMO_PASSWORD_HINT is set but empty' })
	.max(128, { error: 'DEMO_PASSWORD_HINT must be at most 128 characters' });

/**
 * Пароль для карточки входа или `null`, если показывать нечего.
 *
 * `null` — это два случая, и оба законные: установка работает не в
 * демонстрационном режиме (тогда подсказывать чужой пароль не за чем), либо
 * переменная не задана вовсе — так поднимают стенд, пароль которого выдают
 * лично.
 *
 * Заданная, но негодная переменная — не третий такой случай: это ошибка
 * настройки, и она бросается, а не подменяется пустой карточкой.
 */
export function demoPasswordHint(raw: string | undefined, demoMode: boolean): string | null {
	if (!demoMode || raw === undefined || raw === '') {
		return null;
	}

	const result = hintSchema.safeParse(raw);

	if (!result.success) {
		throw new Error(result.error.issues.map((issue) => issue.message).join('; '));
	}

	return result.data;
}
