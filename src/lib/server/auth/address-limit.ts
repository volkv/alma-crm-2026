/**
 * Отказ по лимиту адреса — словами.
 *
 * Хук `rate-limit` не отвечает голым 429: исчерпавший лимит POST на маршрут
 * `(auth)` он разворачивает обратно на ту страницу, с которой пришёл, и
 * объяснить отказ должна она сама. Страниц входа две — пароль и второй шаг, —
 * а счётчик и объяснение у них одни и те же, поэтому и вопрос «исчерпан ли
 * лимит», и текст живут здесь, а не по разу в каждом загрузчике.
 */
import { pluralize } from '$lib/format';
import { addressLimitState, UNKNOWN_ADDRESS } from './lockout';

/**
 * Что показать вместо формы, если с этого адреса больше не пускают, или `null`,
 * когда лимит не выбран и страница работает как обычно.
 *
 * Адрес берётся ровно тем же способом, что у счётчика: пустую строку транспорта
 * заменяет `UNKNOWN_ADDRESS`, иначе страница спрашивала бы про один ключ, а хук
 * считал бы по другому. Аргумент — то, что вернул `getClientAddress()`.
 */
export async function addressLimitNotice(address: string): Promise<string | null> {
	const limit = await addressLimitState(address || UNKNOWN_ADDRESS);

	if (!limit.exhausted) {
		return null;
	}

	// Код ответа человеку ничего не объясняет, а ждать ему всё равно придётся —
	// и он должен знать сколько. Срок знает окно счётчика.
	const minutes = Math.max(1, Math.ceil(limit.remainingSeconds / 60));

	return `Слишком много входов с этого адреса. Попробуйте через ${pluralize(minutes, ['минуту', 'минуты', 'минут'])}`;
}
