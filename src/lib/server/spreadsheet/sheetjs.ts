/**
 * Настроенный экземпляр SheetJS — один на чтение и на запись.
 *
 * Настройка у библиотеки глобальная: `set_cptable` подменяет декодеры строк
 * внутри самой библиотеки. Если вызывать его из нескольких мест, от порядка
 * импортов начнёт зависеть, прочитается ли кириллица, — поэтому вызов ровно
 * один, здесь.
 *
 * Таблицы кодовых страниц (`cpexcel`) лежат отдельным файлом и в ESM-сборке
 * сами не подключаются: об этом сказано в `ParsingOptions.codepage` самой
 * библиотеки. Без них строки старых книг BIFF, где текст лежит не в UTF-16, а
 * в кодовой странице файла, разбираются байт-в-символ и молча превращаются в
 * мусор. Такие книги нам и присылают — цена вопроса полмегабайта таблиц в
 * серверной сборке, в браузер этот модуль не попадает.
 *
 * Подключается именно пространство имён модуля: `set_cptable` зовёт у своего
 * аргумента `utils.decode`, а `utils` — отдельный экспорт `cpexcel`, в
 * экспорте `cptable` его нет.
 */
import * as XLSX from 'xlsx';
import * as cpexcel from 'xlsx/dist/cpexcel.full.mjs';

XLSX.set_cptable(cpexcel);

export { XLSX };
