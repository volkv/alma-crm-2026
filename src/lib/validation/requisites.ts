/**
 * КПП и ОГРН — реквизиты рядом с ИНН. Как и ИНН (`inn.ts`), проверяются по
 * устройству номера, а не только по длине: «12» в поле КПП — опечатка, которую
 * сохранять незачем.
 *
 * Модуль свободен от Zod и серверного кода по той же причине, что и `inn.ts`.
 */

/**
 * КПП — девять знаков: код налогового органа (4 цифры), причина постановки на
 * учёт (2 знака: цифры или заглавные латинские буквы, так ФНС кодирует
 * причины с 2013 года) и порядковый номер (3 цифры).
 */
export function isValidKpp(value: string): boolean {
	return /^\d{4}[\dA-Z]{2}\d{3}$/.test(value);
}

/**
 * ОГРН юридического лица (13 цифр) или ОГРНИП (15 цифр). Последняя цифра —
 * остаток от деления числа из предыдущих цифр на 11 (у ОГРНИП — на 13),
 * взятый по модулю 10. Число не помещается в `number` без потерь у ОГРНИП,
 * поэтому считается в `bigint`.
 */
export function isValidOgrn(value: string): boolean {
	if (!/^\d{13}$|^\d{15}$/.test(value)) {
		return false;
	}

	const divisor = value.length === 13 ? 11n : 13n;
	const body = BigInt(value.slice(0, -1));
	const control = Number((body % divisor) % 10n);

	return control === Number(value.at(-1));
}
