/**
 * Настройки приложения: те значения, которые администратор меняет из интерфейса,
 * а не переменными окружения.
 *
 * Здесь описано, что считается допустимым значением каждой настройки. Значения
 * по умолчанию живут на сервере (`$lib/server/settings`), потому что применяются
 * они там же, где читаются из базы.
 */
import { z } from 'zod';
import { notificationChannelsSchema } from './notifications';
import { rankingWeightsSchema } from './ranking';

export const settingSchemas = {
	/** Текст на странице входа: предупреждение о доступе, контакты поддержки. */
	login_banner: z.object({
		title: z.string().trim().min(1, { error: 'Заголовок не может быть пустым' }).max(200),
		text: z.string().trim().max(2000, { error: 'Текст не длиннее 2000 символов' })
	}),
	/** Через сколько минут бездействия сессия заканчивается. */
	session_idle_minutes: z
		.number({ error: 'Укажите число минут' })
		.int()
		.min(5, { error: 'Не меньше 5 минут' })
		.max(240, { error: 'Не больше 240 минут' }),
	/** Предельный срок жизни сессии независимо от активности. */
	session_absolute_hours: z
		.number({ error: 'Укажите число часов' })
		.int()
		.min(1, { error: 'Не меньше часа' })
		.max(72, { error: 'Не больше 72 часов' }),
	/**
	 * Сколько дней открытая запись стадии может стоять, прежде чем система
	 * напомнит о ней руководителю ответственного. Часы считаются без пауз:
	 * ждать ответа вуза и стоять — разные вещи.
	 *
	 * Ноль допустим и означает «напоминать сразу»: так стенд показывает
	 * эскалацию, не дожидаясь недели. Повтор при этом всё равно не чаще раза в
	 * сутки — см. `$lib/server/notifications/schedule`.
	 */
	stuck_threshold_days: z
		.number({ error: 'Укажите число дней' })
		.int()
		.min(0, { error: 'Не меньше нуля' })
		.max(365, { error: 'Не больше 365 дней' }),
	/**
	 * За сколько дней до окончания лицензии по позиции договора система
	 * напоминает ответственному за вуз, что пора запускать продление. Истёкшая
	 * лицензия напоминает всегда, а руководителю уходит эскалация.
	 *
	 * Ноль — напоминать только об уже истёкших.
	 */
	license_warning_days: z
		.number({ error: 'Укажите число дней' })
		.int()
		.min(0, { error: 'Не меньше нуля' })
		.max(365, { error: 'Не больше 365 дней' }),
	/** Какими каналами уходят напоминания наблюдателей и утренняя сводка. */
	notification_channels: notificationChannelsSchema,
	/**
	 * Утренняя сводка «Мой день»: включена ли и в каком часу уходит.
	 *
	 * Час — **московский**, в отличие от сброса стенда: сводку читает человек в
	 * начале своего рабочего дня, а работает оператор по Москве, где бы ни стоял
	 * сервер. Сводка уходит первым проходом фонового цикла в этот час или позже
	 * в тот же день — одна на сотрудника, день и канал.
	 */
	daily_digest: z.object({
		enabled: z.boolean(),
		hour: z
			.number({ error: 'Укажите час суток' })
			.int()
			.min(0, { error: 'Не меньше 0' })
			.max(23, { error: 'Не больше 23' })
	}),
	/**
	 * Сброс демонстрационных данных по расписанию: включён ли он и в каком часу
	 * суток проходит.
	 *
	 * Час — по часам того сервера, на котором работает приложение: другого
	 * источника времени у фонового прохода нет, а разбирать часовой пояс ради
	 * ночной операции на стенде значило бы завести настройку, которой никто не
	 * управляет.
	 */
	demo_reset_schedule: z.object({
		enabled: z.boolean(),
		hour: z
			.number({ error: 'Укажите час суток' })
			.int()
			.min(0, { error: 'Не меньше 0' })
			.max(23, { error: 'Не больше 23' })
	}),
	/**
	 * Веса рейтинга программ и направлений. Формула — гипотеза команды, и
	 * подбирать её по данным заказчика должен тот, кто их видит, без выпуска.
	 */
	ranking_weights: rankingWeightsSchema,
	/**
	 * Внешние источники паспорта организации: ЕГРЮЛ через Dadata и раздел
	 * `/sveden` сайта вуза. Выключены — форма организации работает вручную и
	 * принимает снимок JSON файлом, а сервер наружу не ходит вовсе.
	 *
	 * Квота — на сотрудника в сутки и считает только настоящие обращения:
	 * ответ из кэша бесплатен. Лимит подсказок у поставщика общий на стенд, и
	 * без квоты его выбрал бы первый же любопытный.
	 */
	enrichment: z.object({
		enabled: z.boolean(),
		dailyQuota: z
			.number({ error: 'Укажите число обращений' })
			.int()
			.min(1, { error: 'Не меньше одного' })
			.max(1000, { error: 'Не больше 1000' })
	})
} as const;

export type SettingKey = keyof typeof settingSchemas;
export type SettingValue<TKey extends SettingKey> = z.output<(typeof settingSchemas)[TKey]>;
