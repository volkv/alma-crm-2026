/** Укрупнённая группа: код `09.00.00` и название, если оно есть в перечне. */
export type FgosGroup = { code: string; name: string | null };

/** Код направления ФГОС: `09.03.01`. Научные специальности (`2.3.5`) — не он. */
const FGOS_CODE = /^(\d{2})\.\d{2}\.\d{2}$/;

/**
 * Группа направления по его коду: первые две цифры кода, остальное — нули
 * (`09.03.01` → `09.00.00`). `null` — код не по перечню ФГОС.
 */
export function fgosGroupOf(code: string | null): FgosGroup | null {
	const head = FGOS_CODE.exec(code?.trim() ?? '')?.[1];

	if (head === undefined) {
		return null;
	}

	return { code: `${head}.00.00`, name: FGOS_GROUP_NAMES[head] ?? null };
}

/** Одна рекомендованная программа школы и почему она подобрана. */
export type ProgramMatch = {
	programId: string;
	programCode: string;
	programName: string;
	directionCode: string;
	priority: number | null;
	group: FgosGroup;
	/** Сколько программ вуза в той же укрупнённой группе. */
	groupCount: number;
	/** Из них — ровно с тем же кодом направления, что у программы школы. */
	sameCodeCount: number;
	/** Объяснение словами: его и видит сотрудник. */
	reason: string;
};

/** Итог подбора: программы вуза по группам и что из программ школы к ним подходит. */
export type ProgramMatchResult = {
	universityGroups: { group: FgosGroup; count: number }[];
	matches: ProgramMatch[];
	/** Программ вуза с кодом не по перечню ФГОС: в подборе не участвуют. */
	universityOutside: number;
	/** Действующих программ школы без кода направления: им не с чем совпасть. */
	schoolWithoutCode: number;
};
