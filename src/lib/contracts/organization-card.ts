/**
 * Карточка организации: что общего у экрана и сервера сверх справочника.
 *
 * Паспорт организации (`$lib/contracts/enrichment`) приносит с сайта вуза два
 * списка — руководителей подразделений и реализуемые программы. Карточка
 * превращает первый в контакты одним щелчком, а второй — в подбор программ
 * школы. Оба превращения объяснимы и повторяемы: имя кандидата разбирается
 * правилом, роль в организации — по словам должности, а подбор программ — по
 * совпадению кодов направлений ФГОС, без догадок.
 */
import { z } from 'zod';
import type { AffiliationRoleKind } from './directory';

/* ------------------------------------------------------------------------- *
 * Кандидаты в контакты.
 * ------------------------------------------------------------------------- */

/**
 * Какого кандидата добавить: подразделение и ФИО так, как их прочитал сайт.
 * Номера в списке для этого не годятся: между чтением и нажатием страница
 * вуза могла перечитаться, и номер указал бы на другого человека.
 */
export const addSiteContactSchema = z.object({
	unit: z.string().trim().min(1, 'Не указано подразделение кандидата').max(1000),
	name: z.string().trim().min(1, 'Не указано ФИО кандидата').max(1000)
});

export type AddSiteContactInput = z.output<typeof addSiteContactSchema>;

/**
 * ФИО в виде для сравнения: регистр, «ё» и точки инициалов не делают двух
 * разных людей. «Иванов И. И.» и «Иванов Иван Иванович» при этом остаются
 * разными — угадывать полное имя по инициалам карточка не берётся.
 */
export function normalizePersonName(value: string): string {
	return value
		.toLocaleLowerCase('ru')
		.replace(/ё/g, 'е')
		.replace(/[.,]/g, ' ')
		.replace(/\s+/g, ' ')
		.trim();
}

/** Инициал или пара инициалов: `И.`, `И.И.`. */
const INITIALS = /^([А-ЯЁA-Z]\.)+$/u;

/**
 * ФИО кандидата по частям. Сайт пишет его одной строкой, обычно «Фамилия Имя
 * Отчество», реже «И. И. Фамилия». `null` — строка из одного слова: без имени
 * человека в справочник не завести, а придумывать его нельзя.
 */
export function splitPersonName(
	value: string
): { lastName: string; firstName: string; middleName: string | null } | null {
	const words = value.trim().split(/\s+/).filter(Boolean);

	if (words.length < 2) {
		return null;
	}

	// «И. И. Иванов»: инициалы впереди — фамилия стоит последней.
	if (INITIALS.test(words[0]) && !INITIALS.test(words[words.length - 1])) {
		return {
			lastName: words[words.length - 1],
			firstName: words.slice(0, -1).join(' '),
			middleName: null
		};
	}

	return {
		lastName: words[0],
		firstName: words[1],
		middleName: words.length > 2 ? words.slice(2).join(' ') : null
	};
}

/**
 * Роль в организации по словам должности. Правило, а не угадывание: четыре
 * должности, которые называются однозначно, остальное — «другое», и роль
 * правится на карточке человека.
 */
export function roleKindFromPost(post: string | null): AffiliationRoleKind {
	const text = (post ?? '').toLocaleLowerCase('ru');

	if (text.includes('проректор')) {
		return 'vice_rector';
	}

	if (text.includes('ректор')) {
		return 'rector';
	}

	if (text.includes('декан')) {
		return 'dean';
	}

	if (/зав(едующ\S*|\.)?\s*кафедр/.test(text)) {
		return 'head_of_department';
	}

	return 'other';
}

