/**
 * Вход в систему и пользователи.
 *
 * Схема формы входа одна на браузер и на сервер: сообщение, которое человек
 * видит рядом с полем, и сообщение, по которому сервер отказывает, обязаны
 * совпадать. Требования к паролю здесь не описаны — они приходят из настройки
 * `password_policy` и проверяются на сервере (`$lib/server/auth/password`),
 * потому что администратор меняет их без пересборки приложения.
 */
import { z } from 'zod';

/**
 * Потолок длины пароля. Argon2 считает хеш от входа любой длины, поэтому предел
 * нужен не алгоритму, а серверу: без него один запрос с мегабайтным «паролем»
 * занимает память и время.
 */
export const PASSWORD_MAX_LENGTH = 200;

export const loginSchema = z.object({
	email: z.email({ error: 'Проверьте адрес электронной почты' }),
	password: z
		.string({ error: 'Введите пароль' })
		.min(1, { error: 'Введите пароль' })
		.max(PASSWORD_MAX_LENGTH, { error: `Пароль не длиннее ${PASSWORD_MAX_LENGTH} символов` })
});

export type LoginInput = z.output<typeof loginSchema>;

/**
 * Код из приложения-аутентификатора: шесть цифр, пробелы между группами
 * допустимы — приложения показывают код именно так.
 *
 * Длина повторена здесь числом, а не взята из `$lib/server/auth/totp`:
 * контракт читает и браузер, а серверные модули туда не попадают. Что эти два
 * числа одинаковы, сторожит модульный тест — он проверяет схему кодом, который
 * посчитал сам алгоритм.
 */
export const totpCodeSchema = z.object({
	code: z
		.string({ error: 'Введите код из приложения' })
		.trim()
		// Пробел между группами — то, как код показывает приложение; пробелы
		// внутри групп кодом не являются.
		.regex(/^\d{3} ?\d{3}$/, { error: 'Код состоит из шести цифр' })
});

export type TotpCodeInput = z.output<typeof totpCodeSchema>;

/**
 * Второй шаг входа: код из приложения **или** резервный код. Какой именно
 * пришёл, решает сервер — человеку на этом шаге предлагается одно поле, потому
 * что резервный код он достаёт ровно тогда, когда приложения под рукой нет, и
 * переключатель «у меня другой код» на форме входа ничего не объясняет.
 */
export const secondFactorSchema = z.object({
	code: z
		.string({ error: 'Введите код' })
		.trim()
		.min(1, { error: 'Введите код' })
		.max(64, { error: 'Это не похоже ни на код, ни на резервный код' })
});

export type SecondFactorInput = z.output<typeof secondFactorSchema>;

/** Состояние второго фактора у учётной записи в том виде, в каком его показывает профиль. */
export type MfaStateView = {
	enabled: boolean;
	enrolledAt: Date | null;
	/** Сколько резервных кодов осталось неиспользованными. */
	backupCodesLeft: number;
};

/** Пользователь в списке управления доступом. Хеш пароля наружу не выходит. */
export type UserView = {
	id: string;
	email: string;
	fullName: string;
	roleId: string;
	roleName: string;
	isActive: boolean;
	isDemo: boolean;
	lastLoginAt: Date | null;
	createdAt: Date;
};

/**
 * Строка списка пользователей вместе с состоянием второго фактора. Состояние
 * приходит не из `listUsers`, а из модуля MFA: раздел показывает их рядом, но
 * собираются они порознь.
 */
export type UserWithMfa = UserView & { mfaEnabled: boolean };

/** Учётная запись публичной демонстрации в том виде, в каком её показывает вход. */
export type DemoAccount = {
	roleId: string;
	roleName: string;
};
