import type { ParamMatcher } from '@sveltejs/kit';

/**
 * Идентификаторы записей в адресах — UUID, и маршрутизатор проверяет это до
 * того, как адрес дойдёт до загрузчика.
 *
 * Без проверки `/organizations/abc` доезжал бы до запроса, где PostgreSQL
 * отказывался разбирать `abc` как `uuid`, и человек видел бы пятисотую вместо
 * «страницы нет». Формат проверяется целиком, включая вид версии и варианта:
 * строка, которая не может быть нашим идентификатором, — это не запись вне
 * области доступа, а другой адрес.
 */
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export const match: ParamMatcher = (param) => UUID.test(param);
