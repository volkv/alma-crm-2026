import { browser } from '$app/environment';
import type { InteractionViewMode } from '$lib/contracts/interactions';

/**
 * Имя признака «чем смотрю список». Читают его обе стороны: браузер пишет
 * выбор, сервер по нему сразу отдаёт нужное представление.
 */
export const VIEW_COOKIE = 'lct_crm_interactions_view';

/** Год: выбор представления — привычка, а не состояние одного захода. */
const MAX_AGE = 60 * 60 * 24 * 365;

/**
 * Чем человек смотрит список взаимодействий — таблицей или доской. Выбор живёт
 * в адресе (ссылкой делятся вместе с представлением), но между заходами в
 * раздел адреса нет, и «как обычно» — это то, что было выбрано в прошлый раз.
 *
 * Признак личный и никому больше не виден, но лежит в куке, а не в
 * `localStorage`: хранилище браузера серверу не видно, и вспомнить выбор
 * получилось бы только после того, как страница ожила, — то есть показав на
 * мгновение таблицу и подменив её доской. Куку сервер читает вместе с запросом
 * и сразу собирает то представление, которое просили.
 */
export function storeView(view: InteractionViewMode) {
	if (!browser) {
		return;
	}

	// `SameSite=Lax` — признак читается при обычном переходе по ссылке, и этого
	// достаточно; отдавать его чужим сайтам незачем.
	document.cookie = `${VIEW_COOKIE}=${view}; path=/; max-age=${MAX_AGE}; samesite=lax`;
}

/**
 * Запомненный выбор из строки кук. Непонятное значение — не ошибка, а просто
 * «не доска»: раздел открывается обычной таблицей.
 */
export function storedView(cookie: string | undefined): InteractionViewMode {
	return cookie === 'board' ? 'board' : 'table';
}
