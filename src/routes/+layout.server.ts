import type { LayoutServerLoad } from './$types';

/**
 * Идентификатор запроса — единственное, что нужно любой странице независимо от
 * раздела, включая ту, что рисуется вместо страницы.
 *
 * Ожидаемый отказ (403 от прав, 404 от сервиса) до `handleError` не доходит:
 * SvelteKit отдаёт тело, которое написал `error()`, и класть туда `requestId`
 * пришлось бы в каждом загрузчике. Отсюда он виден всем, в том числе странице
 * ошибки — её SvelteKit рисует поверх корневого макета даже тогда, когда
 * маршрута не нашлось вовсе.
 */
export const load: LayoutServerLoad = ({ locals }) => ({ requestId: locals.requestId });
