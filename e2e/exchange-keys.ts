/**
 * Обмен прогона: ключи доступа имитаторов, имена подключений и секрет подписи.
 *
 * Значения объявлены здесь, а не набраны в двух местах, потому что у каждого из
 * них два конца. Ключ обмена заводит сид (`scripts/seed/api-keys.ts`) из
 * `EXCHANGE_API_KEY_CMS` и `EXCHANGE_API_KEY_LMS`, а представляется им имитатор
 * (`CRM_API_KEY` в `docker-compose.yml`): разойдись эти значения — имитатор
 * стучится в CRM ключом, которого она не знает. Секретом подписывает исходящие
 * CRM, а проверяет их имитатор. Имя экземпляра CRM сверяет с полем `source`
 * входящего сообщения, а ставит его туда имитатор.
 *
 * На стенде их задаёт развёртывание, через `.env`, и это правильно: ключ стенда
 * — настоящий ключ доступа. Прогон так жить не может: `.env` в репозитории нет и
 * быть не должно, а прогон, зелёный от чужого файла на чужой машине, не
 * проверяет ничего. Поэтому у прогона значения свои и постоянные — их читает и
 * окружение сервера прогона (`playwright.config.ts`, оттуда их берёт сид), и
 * окружение `docker compose up` (`e2e/stack.ts`, оттуда их берут имитаторы).
 *
 * Секретом эти строки не являются: они открывают базу прогона, которую сид
 * заливает синтетикой заново, и в развёртывание не попадают — образ собирается
 * без `e2e/`, а `docker-compose.yml` читает переменные окружения, не этот файл.
 */

