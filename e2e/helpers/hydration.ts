import { expect, type Page } from '@playwright/test';

/**
 * Ожидание ожившей страницы.
 *
 * Разметку страница получает с сервера готовой, а обработчики к ней развешивает
 * браузер — и между этими двумя моментами страница выглядит рабочей, но ничего
 * не умеет: нажатие на её собственную кнопку не доходит до компонента, набранный
 * текст остаётся в разметке и не попадает в данные формы, а форма без `use:enhance`
 * уходит обычным POST-ом на `?/action` и уводит страницу на другой адрес
 * («Всплывающие слои» в `docs/development.md`).
 *
 * Признак «ожила» ставит корневой layout: `data-hydrated` на `<body>` после
 * монтирования. Ждать его — не то же самое, что `networkidle` или пауза:
 * загрузка файлов ничего не говорит о том, смонтировано ли приложение, а пауза
 * закладывается на скорость машины, которая под шестнадцатью рабочими процессами
 * бывает какой угодно.
 */
export async function waitForHydration(page: Page): Promise<void> {
	// Пятнадцать секунд, а не пять по умолчанию: сборка отдаёт свои файлы быстро,
	// но на занятой машине разбор и монтирование занимают заметно больше.
	await expect(page.locator('body[data-hydrated]')).toBeAttached({ timeout: 15_000 });
}
