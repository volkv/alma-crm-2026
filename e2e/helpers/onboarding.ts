import { expect, type Page } from '@playwright/test';

/**
 * Закрыть подсказки первого входа так, как их закрывает человек.
 *
 * Признак «подсказки показаны» лежит в браузере и ставится самим продуктом,
 * когда тур прошли или пропустили. Поэтому прогон нажимает «Пропустить», а не
 * подкладывает значение в хранилище: скрытого выключателя в коде продукта нет и
 * быть не должно — проверялось бы тогда не то приложение, которое увидит
 * человек. Заодно каждая сессия прогона доказывает, что тур этой роли вообще
 * открывается.
 *
 * Зовётся везде, где проверка входит по ходу дела: сохранённые сессии проходят
 * через это же в глобальном сетапе, и для них подсказок уже нет.
 */
export async function skipOnboardingTour(page: Page): Promise<void> {
	const tour = page.getByTestId('onboarding-tour');

	// Тур открывается после того, как страница ожила: на занятой машине это
	// заметно дольше пяти секунд умолчания.
	await expect(tour).toBeVisible({ timeout: 15_000 });
	await tour.getByRole('button', { name: 'Пропустить' }).click();
	await expect(tour).toBeHidden();
}
