/**
 * Стек прогона: сервисы из `docker-compose.yml`, поднятые с тем же обменом,
 * который знает сервер прогона.
 *
 * Отдельным скриптом, а не строкой в `package.json`, потому что поднимать стек
 * приходится со значениями: имитаторы представляются в CRM ключами обмена, те
 * же ключи заводит сид прогона, и набранные дважды они однажды разъедутся.
 * Значения объявлены один раз (`e2e/exchange-keys.ts`) и расходятся отсюда в
 * окружение Compose, а из него — имитаторам.
 *
 * Окружение процесса старше `.env` каталога, поэтому прогон не зависит от того,
 * что лежит в `.env` разработчика, и одинаково работает там, где `.env` нет
 * вовсе, — в чистой копии и в CI.
 *
 * Приложение поднимает не этот скрипт: его собирает и запускает сам Playwright
 * (`webServer` в `playwright.config.ts`) — на своём порту, со своей базой и из
 * рабочей копии, а не из образа. Контейнер `app` прогону не нужен.
 */
import { spawnSync } from 'node:child_process';
import { E2E_EXCHANGE_ENV } from './exchange-keys.ts';

/** Сервисы, без которых прогон не начинается. */
const SERVICES = [
	'postgres',
	'redis',
	'gotenberg',
	'minio',
	'keycloak',
	// Почтовый сервер: уведомление о зависшем взаимодействии уходит по-настоящему,
	// по SMTP, и проверка читает письмо из его API — «кнопка нажалась» доставку
	// не доказывает.
	'mailpit',
	'mock-cms',
	'mock-lms'
] as const;

const options = {
	cwd: new URL('..', import.meta.url).pathname,
	env: { ...process.env, ...E2E_EXCHANGE_ENV },
	stdio: 'inherit'
} as const;

function compose(...args: string[]): void {
	const result = spawnSync('docker', ['compose', ...args], options);

	if (result.error !== undefined) {
		// Запустить не удалось вовсе — это не отказ сервиса, а отсутствующий или
		// недоступный Docker, и знать об этом надо целиком.
		throw result.error;
	}

	if (result.status !== 0) {
		// Compose уже сказал в свой поток, что случилось; второй раз то же самое
		// стеком Node — шум, а не диагностика. Наружу уходит код возврата.
		process.exit(result.status ?? 1);
	}
}

// `--wait`: дальше идёт сборка приложения, миграции и заливка, и начинаться они
// должны против готовых сервисов, а не против поднимающихся.
//
// Изменившееся окружение пересоздаёт контейнер: Compose сверяет описание службы
// с тем, из которого контейнер поднят, и имитатор, оставшийся от прогона с
// другим ключом, поднимается заново с этим.
compose('up', '-d', '--wait', ...SERVICES);

// Бакеты: задача заводит их и выходит. У прогона свой (`lct-documents-e2e`) —
// файлы проверок и файлы стенда не перемешиваются.
compose('run', '--rm', 'minio-init');
