/*
 * Тема оформления до первой отрисовки.
 *
 * Выбор темы принадлежит устройству, а не учётной записи, поэтому лежит в
 * `localStorage` и серверу неизвестен: страница приезжает светлой, и без этого
 * файла человек с тёмной темой увидел бы вспышку белого на каждой загрузке.
 * Поэтому скрипт стоит в <head> и блокирует отрисовку — работы в нём на одну
 * строку, а атрибут обязан оказаться на <html> раньше первого кадра.
 *
 * Файл отдельный, а не вставлен в `app.html`, из-за CSP: `script-src` — это
 * `self`, а хэши и одноразовые числа SvelteKit проставляет только тем
 * скриптам, которые добавляет сам. Написанный руками встроенный скрипт браузер
 * бы заблокировал.
 *
 * Значение атрибута — всегда `light` или `dark`. Выбор «как в системе»
 * хранится в `localStorage` как `system` и разрешается здесь же: значения
 * тёмной темы в `app.css` от этого лежат в одном блоке, а не в двух.
 *
 * Рядом встаёт второй атрибут — `data-theme-preference`: не что на экране, а
 * что выбрано, вместе с неразрешённым `system`. По нему `app.css` показывает
 * нужный значок на кнопке темы. Сервер выбора не знает и рисует все три значка
 * сразу, поэтому разметка с сервера и разметка после оживления совпадают, а
 * видимым значок делает этот атрибут — уже в первом кадре.
 */
(function () {
	var stored = localStorage.getItem('lct-crm:theme');
	// Умолчание — «как в системе», как и в `src/lib/theme.svelte.ts`.
	var preference = stored === 'light' || stored === 'dark' ? stored : 'system';
	var dark =
		preference === 'dark' ||
		(preference === 'system' && window.matchMedia('(prefers-color-scheme: dark)').matches);

	document.documentElement.dataset.theme = dark ? 'dark' : 'light';
	document.documentElement.dataset.themePreference = preference;
})();
