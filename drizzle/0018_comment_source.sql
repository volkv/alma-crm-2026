-- Источник текста комментария.
--
-- Уничтожение персональных данных стирает свободный текст, который заявитель
-- написал о себе сам в форме на сайте (интерес, комментарий, иногда второй
-- телефон), и не трогает комментарии сотрудников — это содержание работы. По
-- автору их не различить: комментарий заявки подписан тем сотрудником, который
-- принимает входящие, как и его собственные.
--
-- Строки, заведённые до этой колонки, считаются текстом сотрудника. Догадка
-- «первый комментарий взаимодействия, приехавшего из CMS» разошлась бы с
-- правдой на первом же повторе заявки, а пометить чужой текст на уничтожение
-- хуже, чем оставить его помеченным как есть.
CREATE TYPE "public"."comment_source" AS ENUM('manual', 'application_intake');--> statement-breakpoint
ALTER TABLE "comments" ADD COLUMN "source" "comment_source" DEFAULT 'manual' NOT NULL;
