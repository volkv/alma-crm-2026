-- Имена двух базовых пространств и процессов говорят, чем в них занимаются.
--
-- «Учебные заведения» и «Физические и юридические лица» называли не работу, а
-- контрагента: место в меню читалось как справочник, а не как процесс. Пара
-- становится «Работа с ВУЗ» и «Коммерческое обучение» — по делу, которое там
-- ведут. Первое имя короткое намеренно: заголовок секции стоит в боковой панели
-- одной строкой и длинное обрезается многоточием.
--
-- Ключи не трогаются: они стоят сегментом адреса и уже разосланы ссылками.
-- Переименование идёт по старому значению, а не по ключу: имя правят и руками,
-- и заказчик, переименовавший пространство по-своему, отменять это не просил.

-- 1. Пространства: имя видно в меню и в заголовке доски.
UPDATE "workspaces" SET "name" = 'Работа с ВУЗ', "updated_at" = now()
WHERE "key" = 'b2b' AND "name" = 'Учебные заведения';--> statement-breakpoint
UPDATE "workspaces" SET "name" = 'Коммерческое обучение', "updated_at" = now()
WHERE "key" = 'b2c' AND "name" = 'Физические и юридические лица';--> statement-breakpoint

-- 2. Процессы: до 0020 имя процесса было именем места и переехало оттуда, так
-- что и старое значение здесь то же самое.
UPDATE "workflows" SET "name" = 'Работа с ВУЗ', "updated_at" = now()
WHERE "key" = 'b2b' AND "name" = 'Учебные заведения';--> statement-breakpoint
UPDATE "workflows" SET "name" = 'Коммерческое обучение', "updated_at" = now()
WHERE "key" = 'b2c' AND "name" = 'Физические и юридические лица';--> statement-breakpoint

-- 3. Редакции хранят имя процесса на момент публикации. Заголовок берётся из
-- процесса, но следующая правка пойдёт от редакции — оставить в ней прежнее имя
-- значило бы вернуть его первой же публикацией.
UPDATE "process_revisions" r SET "name" = f."name"
FROM "workflows" f
WHERE f."id" = r."workflow_id"
	AND f."key" IN ('b2b', 'b2c')
	AND r."name" IN ('Учебные заведения', 'Физические и юридические лица', 'Взаимодействие с учебным заведением', 'Обучение физических и юридических лиц');
