-- Ключи сравнения контактов человека.
--
-- Почта и телефон переезжают в зашифрованный вид (`enc:v1:…`, AES-256-GCM,
-- ключ — в окружении установки), а шифртекст одного и того же значения каждый
-- раз разный: сравнивать по нему нельзя. Поэтому рядом ложатся два
-- детерминированных ключа — HMAC-SHA256 по нормализованному значению, — и по
-- ним работают дедупликация заявок с сайта, дедупликация импорта каталога и
-- поиск по точному контакту.
--
-- Индексы не уникальные: один и тот же адрес встречается у двух записей
-- справочника (контакт вуза и он же заявитель с сайта), и разводит их
-- организация, а не почта.
--
-- Сами значения эта миграция не трогает: шифрует их шаг `scripts/migrate.ts`
-- сразу после применения миграций — SQL не знает ни ключа, ни алгоритма.

